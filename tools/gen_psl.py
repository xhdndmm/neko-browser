#!/usr/bin/env python3
"""Generates src/security/src/public_suffix_data.inc from the Public Suffix
List (https://publicsuffix.org/list/public_suffix_list.dat).

The PSL is the standard cookie/origin scoping data every browser embeds
(RFC 6265 §5.3 rejects Domain= cookies for public suffixes; document.domain
needs the registrable domain).  The list is MPL 2.0 -- the generated file
carries the license header.

Usage:
    python3 tools/gen_psl.py [path/to/public_suffix_list.dat]

Regeneration: download a fresh list and rerun:
    curl -s https://publicsuffix.org/list/public_suffix_list.dat -o /tmp/psl.dat
    python3 tools/gen_psl.py /tmp/psl.dat

Output: a .inc with kIcannRules / kPrivateRules, each sorted so the matcher
can binary-search.  Rules keep their PSL form ('com', 'co.uk', '*.ck',
'!www.ck'); comments, blanks and the section markers are dropped.
"""
import sys
import re

DEFAULT = "/tmp/opencode/psl.dat"
OUT = "src/security/src/public_suffix_data.inc"


def parse(path):
    icann, private = [], []
    section = None
    version = ""
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line.startswith("// VERSION:"):
                version = line[len("// VERSION:"):].strip()
            if line == "// ===BEGIN ICANN DOMAINS===":
                section = icann
                continue
            if line == "// ===BEGIN PRIVATE DOMAINS===":
                section = private
                continue
            if line in ("// ===END ICANN DOMAINS===", "// ===END PRIVATE DOMAINS==="):
                section = None
                continue
            if not line or line.startswith("//"):
                continue
            if section is not None:
                section.append(line.lower())
    icann.sort()
    private.sort()
    return version, icann, private


def emit(version, icann, private):
    out = []
    out.append("// GENERATED by tools/gen_psl.py -- DO NOT EDIT.")
    out.append("// Source: https://publicsuffix.org/list/public_suffix_list.dat")
    out.append(f"// VERSION: {version}")
    out.append("// License: Mozilla Public License 2.0 (the list itself); see")
    out.append("// https://mozilla.org/MPL/2.0/.  Regenerate with tools/gen_psl.py.")
    out.append("")
    for name, rules in (("kIcannRules", icann), ("kPrivateRules", private)):
        out.append(f"constexpr const char* {name}[] = {{")
        for rule in rules:
            out.append(f'    "{rule}",')
        out.append("};")
        out.append("")
    return "\n".join(out)


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else DEFAULT
    version, icann, private = parse(path)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(emit(version, icann, private))
    print(f"wrote {OUT}: {len(icann)} ICANN + {len(private)} private rules ({version})")


if __name__ == "__main__":
    main()
